SAMPLE_KB_DOCUMENT = """
# FreshWeb-RAG Architecture and Specification

FreshWeb-RAG is an enterprise-grade Retrieval-Augmented Generation system.
It dynamically chooses between five retrieval routes:
1. no_retrieval: General definitions and conversational exchanges.
2. static_kb: Domain queries answered using internal vectorized documents.
3. web_only: Highly time-sensitive queries requiring live external data.
4. hybrid: Ambiguous internal knowledge supplemented by live web intelligence.
5. multi_hop: Complex comparative queries decomposed into sub-questions.

The system utilizes Qdrant as its vector store with dense embeddings, BM25 for sparse retrieval,
and a cross-encoder reranker (ms-marco-MiniLM-L-6-v2) for top-k precision.
All factual statements generated by the answer synthesizer must be backed by verifiable citations.
"""


async def seed():
    print(f"Seeding demo data for user: {DEMO_USER_ID}")
    print(f"Database URL: {settings.database_url}")
    print(f"Qdrant URL: {settings.qdrant_url}")

    # Seed memories
    print("\n--- Seeding Long-Term Memories ---")
    seeded_memories = 0
    for mem in SAMPLE_MEMORIES:
        try:
            mem_id = await store_memory(
                user_id=DEMO_USER_ID,
                memory_type=mem["memory_type"],
                content=mem["content"],
                importance_score=mem["importance_score"],
                provenance=mem["provenance"],
                db=None,  # Indexes in Qdrant; if DB available, pass session
            )
            print(f"  [✓] Seeded {mem['memory_type'].upper()}: \"{mem['content'][:60]}...\" (id: {mem_id})")
            seeded_memories += 1
        except Exception as e:
            print(f"  [!] Skipped memory (Qdrant offline): {e}")

    # Save sample doc to disk for manual or automated upload
    sample_doc_path = Path("data/sample_architecture_doc.md")
    sample_doc_path.parent.mkdir(exist_ok=True)
    sample_doc_path.write_text(SAMPLE_KB_DOCUMENT.strip(), encoding="utf-8")
    print(f"\n[✓] Sample KB document generated at: {sample_doc_path}")

    print("\n--- Summary ---")
    print(f"Total memories processed: {len(SAMPLE_MEMORIES)}")
    print("Demo data setup completed.")


if __name__ == "__main__":
    asyncio.run(seed())

